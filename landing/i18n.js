function currentLang() {
  return localStorage.getItem("nextsync-lang") ||
    (new URLSearchParams(location.search).get("hl")) ||
    ((navigator.language || "es").toLowerCase().startsWith("en") ? "en" : "es");
}

function applyLang(lang) {
  const dict = I18N[lang] || I18N.es;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = dict[el.dataset.i18n];
    if (v !== undefined) el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-svg]").forEach(el => {
    const v = dict[el.dataset.i18nSvg];
    if (v !== undefined) el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    const v = dict[el.dataset.i18nAria];
    if (v !== undefined) el.setAttribute("aria-label", v);
  });
  localStorage.setItem("nextsync-lang", lang);
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}
