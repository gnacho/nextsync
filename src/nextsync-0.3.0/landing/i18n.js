function currentLang() {
  return localStorage.getItem("nextsync-lang") ||
    (new URLSearchParams(location.search).get("hl")) ||
    ((navigator.language || "es").toLowerCase().startsWith("en") ? "en" : "es");
}

function applyLang(lang) {
  const dict = I18N[lang] || I18N.es;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = dict[el.dataset.i18n];
    if (v !== undefined) el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-svg]").forEach(el => {
    const v = dict[el.dataset.i18nSvg];
    if (v !== undefined) el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    const v = dict[el.dataset.i18nAria];
    if (v !== undefined) el.setAttribute("aria-label", v);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach(el => {
    const v = dict[el.dataset.i18nAlt];
    if (v !== undefined) el.setAttribute("alt", v);
  });
  if (dict["meta.title"]) document.title = dict["meta.title"];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict["meta.description"]) metaDesc.setAttribute("content", dict["meta.description"]);
  // Each language is reachable at its own URL, so the canonical and og:url
  // must point at the variant being shown, not always at the Spanish one.
  const canonicalUrl = "https://nextsync.cloudless.club/" + (lang === "en" ? "?hl=en" : "");
  const canonical = document.querySelector('link[rel="canonical"]');
  if (canonical) canonical.setAttribute("href", canonicalUrl);
  const ogUrl = document.querySelector('meta[property="og:url"]');
  if (ogUrl) ogUrl.setAttribute("content", canonicalUrl);
  localStorage.setItem("nextsync-lang", lang);
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}
